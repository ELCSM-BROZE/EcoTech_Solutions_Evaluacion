"""Configuración y conexiones a Oracle Database."""

from contextlib import contextmanager
import os
from typing import Iterator

import oracledb
from dotenv import load_dotenv


class Database:
    """Administra conexiones y la tabla de empleados en Oracle."""

    def __init__(
        self,
        user: str | None = None,
        password: str | None = None,
        dsn: str | None = None,
    ) -> None:
        load_dotenv()
        self.user = user if user is not None else os.getenv("ORACLE_USER")
        self.password = password if password is not None else os.getenv("ORACLE_PASSWORD")
        self.dsn = dsn if dsn is not None else os.getenv("ORACLE_DSN")

    @contextmanager
    def connection(self) -> Iterator[oracledb.Connection]:
        if not self.user or not self.password or not self.dsn:
            raise ValueError(
                "Configura ORACLE_USER, ORACLE_PASSWORD y ORACLE_DSN en el archivo .env."
            )

        connection = oracledb.connect(
            user=self.user,
            password=self.password,
            dsn=self.dsn,
        )
        try:
            yield connection
            connection.commit()
        except Exception:
            connection.rollback()
            raise
        finally:
            connection.close()

    def initialize(self) -> None:
        with self.connection() as connection:
            cursor = connection.cursor()
            try:
                cursor.execute(
                    "SELECT table_name FROM user_tables WHERE table_name = :table_name",
                    {"table_name": "EMPLOYEES"},
                )
                if cursor.fetchone() is None:
                    cursor.execute(
                        """
                        CREATE TABLE employees (
                            employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY
                                PRIMARY KEY,
                            full_name VARCHAR2(100) NOT NULL,
                            email VARCHAR2(254) NOT NULL UNIQUE,
                            position VARCHAR2(80) NOT NULL,
                            salary NUMBER(12, 2) NOT NULL CHECK (salary >= 0)
                        )
                        """
                    )
            finally:
                cursor.close()
